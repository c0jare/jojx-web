// Generates directors-data.js for the design preview, from Sanity plus the Vimeo API.
// The design imports ./directors-data.js and reads DIRECTORS (keyed by slug) and ORDER.
//
//   T=<sanity read token> V=<vimeo token> node build-data.mjs
//
// Clip URLs are resolved fresh each run because Vimeo's file links are tied to the account,
// not to the page. Re-run this whenever the roster or a director's work order changes.

import {createClient} from '@sanity/client'
import {writeFileSync} from 'node:fs'

const T = process.env.T, V = process.env.V
if (!T || !V) throw new Error('Need T (Sanity token) and V (Vimeo token)')
const c = createClient({projectId: 'q198rjlt', dataset: 'production', token: T, apiVersion: '2025-02-19', useCdn: false})

const data = await c.fetch(`{
  "order": *[_id=="directorsPage"][0].roster[]->{"slug": slug.current},
  "directors": *[_type=="director"]{
    name, "slug": slug.current, bio, abstract,
    "reel": reel.vimeoUrl,
    "cover": coverImage.asset->url,
    links,
    "work": work[]->{brand, title, vimeoUrl, "clip": loop.vimeoUrl, "still": still.asset->url}
  }
}`)

const vid = (u) => (u && u.match(/vimeo\.com\/(?:video\/)?(\d+)/) || [])[1]

// one lookup per Vimeo id, then pick the rendition that suits where the clip is used
const cache = new Map()
const wanted = new Set()
for (const d of data.directors) {
  if (vid(d.reel)) wanted.add(vid(d.reel))
  for (const w of d.work || []) if (vid(w.clip)) wanted.add(vid(w.clip))
}
const queue = [...wanted]
console.log(`resolving ${queue.length} Vimeo clips…`)
let done = 0
async function worker() {
  while (queue.length) {
    const id = queue.shift()
    for (let attempt = 0; attempt < 4; attempt++) {
      const r = await fetch(`https://api.vimeo.com/videos/${id}?fields=files.rendition,files.link,files.width`, {
        headers: {Authorization: `bearer ${V}`},
      })
      if (r.status === 429) { await new Promise((s) => setTimeout(s, 8000)); continue }
      const j = await r.json().catch(() => ({}))
      cache.set(id, j.files || [])
      break
    }
    if (++done % 40 === 0) console.log(`  ${done}/${wanted.size}`)
    await new Promise((s) => setTimeout(s, 110))
  }
}
await Promise.all(Array.from({length: 5}, worker))

// grid clips stay light; the full-bleed reel gets the bigger file
const pick = (url, prefer) => {
  const files = cache.get(vid(url)) || []
  if (!files.length) return ''
  const byName = (r) => files.find((f) => f.rendition === r)
  const order = prefer === 'reel' ? ['1080p', '720p', '540p'] : ['720p', '540p', '1080p', '360p']
  for (const r of order) { const f = byName(r); if (f?.link) return f.link }
  const progressive = files.filter((f) => f.link && f.rendition !== 'adaptive')
  return progressive.sort((a, b) => (a.width || 0) - (b.width || 0))[0]?.link || ''
}

// the design sets the first name in italic and the last name in roman; single-word
// names (JONES, Per-Hampus) are treated as a last name so nothing is italicised alone
const splitName = (n) => {
  const parts = String(n || '').trim().split(/\s+/)
  return parts.length < 2 ? {first: '', last: parts[0] || ''} : {first: parts.slice(0, -1).join(' '), last: parts.at(-1)}
}
const findLink = (links, kind) =>
  (links || []).find((l) => new RegExp(kind, 'i').test(l.label || '') || new RegExp(kind, 'i').test(l.url || ''))

const DIRECTORS = {}
for (const d of data.directors) {
  const {first, last} = splitName(d.name)
  const site = findLink(d.links, 'website|\\.com')
  const ig = findLink(d.links, 'insta')
  DIRECTORS[d.slug] = {
    first, last,
    lead: d.bio || '',
    bio: d.abstract || '',
    reel: pick(d.reel, 'reel'),
    still: d.cover || '',
    site: site ? site.text || site.label : '',
    siteUrl: site ? site.url : '',
    ig: ig ? ig.text || ig.label : '',
    igUrl: ig ? ig.url : '',
    work: (d.work || []).map((w) => ({
      client: w.brand,
      title: w.title || '',
      still: w.still || '',
      clip: pick(w.clip),
      filmUrl: w.vimeoUrl || '',
    })),
  }
}
const ORDER = (data.order || []).map((o) => o.slug).filter((s) => DIRECTORS[s])
for (const s of Object.keys(DIRECTORS)) if (!ORDER.includes(s)) ORDER.push(s)

const out = `// Generated by build-data.mjs from Sanity + the Vimeo API. Do not edit by hand.
// Regenerate after changing the roster, a director's work order, or any clip.
export const DIRECTORS = ${JSON.stringify(DIRECTORS, null, 1)};
export const ORDER = ${JSON.stringify(ORDER)};
`
writeFileSync(new URL('./directors-data.js', import.meta.url), out)

const missingReel = ORDER.filter((s) => !DIRECTORS[s].reel)
const missingClips = ORDER.flatMap((s) => DIRECTORS[s].work.filter((w) => !w.clip).map((w) => `${s}/${w.client}`))
console.log(`\nwrote directors-data.js: ${ORDER.length} directors, ${ORDER.reduce((a, s) => a + DIRECTORS[s].work.length, 0)} spots`)
if (missingReel.length) console.log(`  no reel file: ${missingReel.join(', ')}`)
if (missingClips.length) console.log(`  no clip file: ${missingClips.join(', ')}`)
