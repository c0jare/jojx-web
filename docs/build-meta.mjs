// Adds the link-preview tags (title, description, share card) to every page.
// iMessage, Slack, WhatsApp and the rest read these; without them a shared link shows
// nothing but the bare URL.
//
//   node build-meta.mjs
//
// BASE must be the public address the site is served from. Change it at DNS cutover:
// preview links only resolve if og:image is an absolute URL on the same host.

import {readFileSync, writeFileSync} from 'node:fs'

const BASE = process.env.BASE || 'https://c0jare.github.io/jojx-web'
const TITLE = 'JOJX'
const DESC = 'We represent award-winning directors and make films for brands.'

const tags = (page) => `  <title>${TITLE}</title>
  <meta name="description" content="${DESC}">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="${TITLE}">
  <meta property="og:title" content="${TITLE}">
  <meta property="og:description" content="${DESC}">
  <meta property="og:url" content="${BASE}/">
  <meta property="og:image" content="${BASE}/assets/share.png">
  <meta property="og:image:type" content="image/png">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta property="og:image:alt" content="JOJX">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:title" content="${TITLE}">
  <meta name="twitter:description" content="${DESC}">
  <meta name="twitter:image" content="${BASE}/assets/share.png">
  <link rel="icon" href="${BASE}/assets/share.png">`

const BEGIN = '<!-- BEGIN share (generated by build-meta.mjs) -->'
const END = '<!-- END share -->'

for (const page of ['home.html', 'mobile.html']) {
  const url = new URL(`./${page}`, import.meta.url)
  let html = readFileSync(url, 'utf8')
  const block = `${BEGIN}\n${tags(page)}\n  ${END}`
  if (html.includes(BEGIN)) {
    html = html.replace(new RegExp(`${BEGIN}[\\s\\S]*?${END}`), block)
  } else {
    // sits right after the charset so crawlers hit it in the first bytes
    const anchor = html.match(/<meta charset="[^"]*">\s*/i)
    if (!anchor) throw new Error(`no <meta charset> in ${page}`)
    html = html.replace(anchor[0], `${anchor[0]}${block}\n`)
  }
  writeFileSync(url, html)
  console.log(`${page}: share tags written`)
}

// index.html redirects with JavaScript, and most link previewers do not run JavaScript,
// so this is the page they actually read. It carries the same tags.
writeFileSync(new URL('./index.html', import.meta.url), `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
${tags('index.html')}
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="robots" content="noindex">
</head>
<body style="margin:0;background:#fff">
<script>
  // the mobile artboard is a separate design, so pick one before anything paints
  var small = /Android|iPhone|iPad|iPod|Mobile/i.test(navigator.userAgent)
    || (matchMedia('(pointer:coarse)').matches && innerWidth < 900);
  location.replace(small ? 'mobile.html' : 'home.html');
</script>
<noscript><a href="home.html">Open the JOJX site</a></noscript>
</body>
</html>
`)
console.log('index.html: rewritten with share tags')
console.log(`\nshare card: ${BASE}/assets/share.png`)
